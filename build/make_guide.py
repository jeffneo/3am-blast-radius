"""Render the documents from their templates.

No document carries a hand-typed Cypher statement, result or figure:

    {{query B2b}}    the statement, exactly as in queries/*.cypher
    {{result B2b}}   the verified output recorded in build/expected/B2b.txt
    {{f key}}        a figure, from build/facts.py (computed from the recorded results)
    {{n key}}        the same figure with thousands separators

Templates -> documents:

    build/lab-guide.template.md   -> LAB-GUIDE.md      (the attendee guide)
    build/docs/STORYLINE.tmpl.md  -> STORYLINE.md
    build/docs/FACILITATOR.tmpl.md -> FACILITATOR-GUIDE.md (for the people delivering; spoilers)
    build/docs/BLOOM.tmpl.md      -> BLOOM-GUIDE.md      (the eight Bloom search phrases)
    build/docs/README.tmpl.md     -> README.md
    build/docs/MODEL.tmpl.md      -> graph/MODEL.md

Edit the template, never the output. Run after `python3 build/verify.py --record`.
`--check` exits non-zero if any document is stale, and build/verify.py calls it.
"""

from __future__ import annotations

import importlib.util
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = [
    ("build/lab-guide.template.md", "LAB-GUIDE.md"),
    ("build/docs/STORYLINE.tmpl.md", "STORYLINE.md"),
    ("build/docs/FACILITATOR.tmpl.md", "FACILITATOR-GUIDE.md"),
    ("build/docs/BLOOM.tmpl.md", "BLOOM-GUIDE.md"),
    ("build/docs/README.tmpl.md", "README.md"),
    ("build/docs/MODEL.tmpl.md", "graph/MODEL.md"),
]
QUERY_FILES = ["readiness.cypher", "demo-queries.cypher", "hands-on.cypher", "gds.cypher", "bloom.cypher"]
PLACEHOLDER = re.compile(r"\{\{(query|result|f|n) ([\w.*-]+)\}\}")
# Write summaries cypher-shell appends ("Added 1 nodes" on 5.26, "Created 1 node" on 2026.x).
SUMMARY_LINE = re.compile(r"^(added|set|removed|deleted|created)\b.*\d.*$", re.I | re.M)


def load(name: str):
    spec = importlib.util.spec_from_file_location(name, ROOT / f"build/{name}.py")
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod
    spec.loader.exec_module(mod)
    return mod


def render(template: Path, queries: dict[str, str], facts: dict) -> str:
    def sub(m: re.Match) -> str:
        kind, key = m.groups()
        if kind == "query":
            if key not in queries:
                sys.exit(f"{template.name}: unknown query {key}")
            return f"```cypher\n{queries[key]}\n```"
        if kind == "result":
            path = ROOT / "build/expected" / f"{key}.txt"
            if not path.exists():
                sys.exit(f"{template.name}: no recorded result for {key}; run build/verify.py --record")
            text = re.sub(r"\n{3,}", "\n\n", SUMMARY_LINE.sub("", path.read_text())).strip()
            return f"```\n{text}\n```"
        if key not in facts:
            sys.exit(f"{template.name}: unknown fact {key!r}; see build/facts.py")
        v = facts[key]
        return f"{v:,}" if kind == "n" else str(v)

    header = ("<!-- GENERATED by build/make_guide.py from "
              f"{template.relative_to(ROOT)}. Edit the template, not this file. -->\n\n")
    return header + PLACEHOLDER.sub(sub, template.read_text())


def main() -> None:
    verify, facts = load("verify"), load("facts").FACTS
    queries: dict[str, str] = {}
    for f in QUERY_FILES:
        for sid, stmt in verify.statements(ROOT / "queries" / f):
            queries[sid] = stmt
    check = "--check" in sys.argv
    stale = []
    for tmpl, out in DOCS:
        text = render(ROOT / tmpl, queries, facts)
        path = ROOT / out
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(out)
        else:
            path.write_text(text)
            print(f"wrote {out} ({len(PLACEHOLDER.findall((ROOT / tmpl).read_text()))} placeholders)")
    if check:
        if stale:
            sys.exit("stale: " + ", ".join(stale) + ". Run python3 build/make_guide.py")
        print("all documents are up to date")


if __name__ == "__main__":
    main()
